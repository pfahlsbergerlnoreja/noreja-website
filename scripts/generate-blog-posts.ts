/**
 * Generates src/lib/blogPosts.ts — the latest posts of the HubSpot blog, per
 * language, for the blog teaser (src/components/HubSpotBlogTeaser.tsx).
 *
 * Why: the teaser used to fetch the RSS feed in the browser. The feed carries
 * every post in full, so each visit downloaded ~1.5 MB of XML (240 kB over the
 * wire) and parsed it on the main thread, only to show three cards at the
 * bottom of the page. The posts also only appeared after an effect, so the
 * prerendered HTML had a skeleton where crawlers should have found the links.
 *
 * Runs in `prebuild`. If a feed cannot be fetched, the committed file is left
 * as it is and the build goes on with the posts from the last successful run —
 * a blog outage must not take the website deploy down with it. New posts show
 * up on the site with the next deploy.
 */
import { readFileSync, writeFileSync, existsSync } from 'fs';
import { resolve, dirname } from 'path';
import { fileURLToPath } from 'url';
import { JSDOM } from 'jsdom';

const __dirname = dirname(fileURLToPath(import.meta.url));
const outFile = resolve(__dirname, '../src/lib/blogPosts.ts');

const FEEDS = {
  de: 'https://blog.noreja.com/de-de/rss.xml',
  en: 'https://blog.noreja.com/en/rss.xml',
} as const;

/** More than any teaser shows (maxItems defaults to 3), so a page can ask for more. */
const POSTS_PER_LANGUAGE = 6;

/** Cards render the image at most ~400 px wide; 640 covers high-density screens. */
const IMAGE_WIDTH = 640;

type Language = keyof typeof FEEDS;

interface BlogPost {
  title: string;
  link: string;
  pubDate: string;
  description: string;
  author?: string;
  imageUrl?: string;
}

/** "email@domain.com (Name)" or "Name <email@domain.com>" → "Name"; a bare address → nothing. */
function extractAuthorName(raw: string | null | undefined): string | undefined {
  if (!raw) return undefined;

  const nameInParens = raw.match(/\(([^)]+)\)/);
  if (nameInParens) return nameInParens[1].trim();

  const nameBeforeEmail = raw.match(/^([^<]+)</);
  if (nameBeforeEmail) return nameBeforeEmail[1].trim();

  if (/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(raw.trim())) return undefined;

  return raw.trim();
}

/**
 * Featured images are full-size uploads (a 170 kB PNG for a 400 px card).
 * HubSpot resizes and converts anything under /hubfs/ when it is requested
 * through /hs-fs/ with a width — the same image arrives as a ~20 kB WebP.
 */
function resizedImageUrl(url: string): string {
  const parsed = new URL(url);
  if (!parsed.pathname.startsWith('/hubfs/') || parsed.search) return url;
  const name = parsed.pathname.split('/').pop() ?? '';
  return `${parsed.origin}/hs-fs${parsed.pathname}?width=${IMAGE_WIDTH}&name=${encodeURIComponent(name)}`;
}

function parseFeed(xml: string): BlogPost[] {
  const { document } = new JSDOM(xml, { contentType: 'text/xml' }).window;
  if (document.getElementsByTagName('parsererror').length) {
    throw new Error('feed is not well-formed XML');
  }

  const text = (item: Element, tag: string) =>
    item.getElementsByTagName(tag)[0]?.textContent?.trim() ?? '';

  return [...document.getElementsByTagName('item')].slice(0, POSTS_PER_LANGUAGE).map((item) => {
    // The description is the whole post as HTML, led by the featured image.
    const description = text(item, 'description');
    const image =
      item.getElementsByTagName('enclosure')[0]?.getAttribute('url') ??
      description.match(/<img[^>]+src="([^">]+)"/)?.[1];

    return {
      title: text(item, 'title') || 'Untitled',
      link: text(item, 'link') || '#',
      pubDate: text(item, 'pubDate'),
      description:
        description.replace(/<[^>]*>/g, '').replace(/\s+/g, ' ').trim().substring(0, 200) + '...',
      author: extractAuthorName(text(item, 'author') || text(item, 'dc:creator')),
      imageUrl: image ? resizedImageUrl(image) : undefined,
    };
  });
}

async function fetchPosts(language: Language): Promise<BlogPost[]> {
  const response = await fetch(FEEDS[language], {
    headers: { Accept: 'application/rss+xml, application/xml, text/xml' },
    signal: AbortSignal.timeout(30_000),
  });
  if (!response.ok) throw new Error(`HTTP ${response.status}`);
  const posts = parseFeed(await response.text());
  if (posts.length === 0) throw new Error('feed has no items');
  return posts;
}

async function main() {
  const posts = {} as Record<Language, BlogPost[]>;
  for (const language of Object.keys(FEEDS) as Language[]) {
    try {
      posts[language] = await fetchPosts(language);
    } catch (error) {
      const fallback = existsSync(outFile) ? 'keeping the committed posts' : 'no committed posts to fall back on';
      console.warn(`⚠️  blog posts: ${FEEDS[language]} failed (${(error as Error).message}), ${fallback}`);
      return;
    }
  }

  const source = `// GENERATED by scripts/generate-blog-posts.ts — do not edit by hand.
// Run \`npm run generate-blog-posts\` (or \`npm run build\`) to refresh.
//
// The latest posts of blog.noreja.com per language, resolved at build time so
// the blog teaser renders them in the first paint and in the prerendered HTML.

export interface BlogPost {
  title: string;
  link: string;
  pubDate: string;
  description: string;
  author?: string;
  imageUrl?: string;
}

export const blogPosts: Record<'de' | 'en', BlogPost[]> = ${JSON.stringify(posts, null, 2)};
`;

  if (existsSync(outFile) && readFileSync(outFile, 'utf-8') === source) {
    console.log('✅ blog posts: unchanged');
    return;
  }
  writeFileSync(outFile, source);
  console.log(`✅ blog posts: ${posts.de.length} de, ${posts.en.length} en`);
}

main();
